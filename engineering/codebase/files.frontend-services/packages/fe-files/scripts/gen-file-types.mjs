// Writes src/icons/FileTypeTable.ts from the be registry (packages/Formats/Registry/file-types.json), so the be checks
// and the fe icons never disagree on a type. Run after changing the registry; tests/FileTypeTable.test.ts fails while
// the checked-in table and the registry differ.
//   node scripts/gen-file-types.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const registry = new URL(
  '../../../../files.backend-services/packages/Formats/Registry/file-types.json',
  import.meta.url,
);
const table = new URL('../src/icons/FileTypeTable.ts', import.meta.url);

const { types } = JSON.parse(readFileSync(registry, 'utf8'));
const quote = (value) => `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
const rows = types.map((type) => `  [${[type.ext, type.kind, type.label, type.mime].map(quote).join(', ')}],`);

writeFileSync(
  table,
  [
    '// Generated by scripts/gen-file-types.mjs from Files.Formats Registry/file-types.json. Do not edit.',
    "import type { FileKind } from '../contracts/FileKind';",
    '',
    '/** Holds one registry row: extension, kind, icon label and content type. */',
    'export type FileTypeRow = readonly [ext: string, kind: FileKind, label: string, mime: string];',
    '',
    '/** Holds every registry row, in registry order. */',
    'export const fileTypeRows: readonly FileTypeRow[] = [',
    ...rows,
    '];',
    '',
  ].join('\n'),
);
console.log(`[gen:file-types] ${rows.length} rows → src/icons/FileTypeTable.ts`);
